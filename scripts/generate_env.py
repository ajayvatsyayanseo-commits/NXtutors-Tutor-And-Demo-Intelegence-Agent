def build_lead_intake_section(shared_secret: str, existing: dict[str, str]) -> str:
    """The block appended to the Lead Intake `.env`. Adds keys, never rewrites."""
    local_url = "http://localhost:8081/internal/v1/handoff"
    return f"""

{SECTION_HEADER}
# TutorMatch is called as an internal handoff and returns {{"status","reply_text"}}.
# Lead Intake keeps the Meta webhook and the outbound sender.
# TUTOR_MATCHING_AGENT_INTERNAL_SECRET needs a Settings field in app/core/config.py.
TUTOR_MATCHING_AGENT_WEBHOOK_URL={existing.get("TUTOR_MATCHING_AGENT_WEBHOOK_URL") or local_url}
TUTOR_MATCHING_AGENT_INTERNAL_SECRET={shared_secret}
TUTOR_MATCHING_AGENT_TIMEOUT_S=2.0

# Enable when ready to route live traffic (TutorMatch still ships in shadow mode).
# INTEGRATIONS_ENABLED=true
# INTEGRATION_MODE=webhook
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument(
        "--force", action="store_true", help="overwrite an existing TutorMatch .env"
    )
    args = parser.parse_args()

    lead = read_env(LEAD_INTAKE_ENV)
    if not lead:
        print(f"WARNING: no Lead Intake .env at {LEAD_INTAKE_ENV}; using placeholders")

    existing_tm = read_env(TUTOR_MATCH_ENV)
    # Reuse the shared secret if one side already has it, so re-running does not
    # silently break a working pairing.
    shared_secret = (
        existing_tm.get("TMM_INTERNAL_SECRET")
        or lead.get("TUTOR_MATCHING_AGENT_INTERNAL_SECRET")
        or hex_secret()
    )

    demo_cc = read_env(DEMO_CC_ENV)
    if not demo_cc:
        print(f"WARNING: no Demo Command Center .env at {DEMO_CC_ENV}")
    tm_content = build_tutor_match_env(lead, demo_cc, shared_secret)
    if TUTOR_MATCH_ENV.exists() and not args.force and not args.dry_run:
        print(f"SKIP  {TUTOR_MATCH_ENV.name} already exists (use --force to regenerate)")
    elif args.dry_run:
        print(f"WOULD WRITE  {TUTOR_MATCH_ENV}  ({len(tm_content.splitlines())} lines)")
    else:
        TUTOR_MATCH_ENV.write_text(tm_content, encoding="utf-8")
        print(f"WROTE {TUTOR_MATCH_ENV}")

    lead_text = (
        LEAD_INTAKE_ENV.read_text(encoding="utf-8", errors="replace")
        if LEAD_INTAKE_ENV.is_file()
        else ""
    )
    if SECTION_HEADER in lead_text:
        print("SKIP  Lead Intake .env already has the TutorMatch section")
    elif not LEAD_INTAKE_ENV.is_file():
        print(f"SKIP  {LEAD_INTAKE_ENV} not found")
    elif args.dry_run:
        print(f"WOULD APPEND section to {LEAD_INTAKE_ENV}")
    else:
        LEAD_INTAKE_ENV.write_text(
            lead_text.rstrip("\n") + build_lead_intake_section(shared_secret, lead),
            encoding="utf-8",
        )
        print(f"APPENDED TutorMatch section to {LEAD_INTAKE_ENV}")

    print("\nBoth files are gitignored. No secret was printed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
