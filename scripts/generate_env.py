"""Generate the local `.env` for TutorMatch and the paired section for Lead Intake.

Reads the shared infrastructure values out of the Lead Intake `.env` (the same
RDS instance, the same OpenAI account, the same WhatsApp number) and mints fresh
secrets for everything that is TutorMatch-specific.

The paired secrets — `INTERNAL_SECRET` — are written to **both** files with the
same value, because that is the shared secret on the handoff. Everything else is
generated per service.

Both `.env` files are gitignored. This script never prints a secret and never
overwrites a value that already exists in the Lead Intake file.

    uv run python scripts/generate_env.py            # write both
    uv run python scripts/generate_env.py --dry-run  # show what would change
"""

from __future__ import annotations

import argparse
import secrets
import sys
import urllib.parse as urlparse
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
PRODUCTION_AGENTS = HERE.parent
LEAD_INTAKE_ENV = PRODUCTION_AGENTS / "nxtutors-lead-intake-agent" / ".env"
DEMO_CC_ENV = PRODUCTION_AGENTS / "Demo Command Center Agent" / ".env"
TUTOR_MATCH_ENV = HERE / ".env"

SECTION_HEADER = "# ===== NXTUTORS TUTOR INTELLIGENCE (tutor-match-meta) ====="


def read_env(path: Path) -> dict[str, str]:
    if not path.is_file():
        return {}
    values: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, _, value = stripped.partition("=")
        values[key.strip()] = value.strip()
    return values


def hex_secret(nbytes: int = 32) -> str:
    return secrets.token_hex(nbytes)


def derive_postgres_dsn(demo_cc: dict[str, str], lead: dict[str, str]) -> str:
    """Reuse the Demo Command Center database and its application user.

    Preferred over minting a new database because those credentials already
    exist, already have the right grants, and are already reachable from the
    same VPC. TutorMatch keeps its tables in a dedicated **schema**
    (`TMM_POSTGRES_SCHEMA`), so the two services share a database without
    sharing a namespace — including `alembic_version`, which is one row per
    schema and would otherwise have two services fighting over one head.
    """
    dsn = demo_cc.get("DATABASE_URL", "")
    if dsn.startswith("postgresql"):
        # Already `postgresql+asyncpg://…` in the Demo CC env.
        return dsn
    # Fall back to assembling it from the discrete DEMO_COMMAND_CENTER_DB_* keys.
    host = demo_cc.get("DEMO_COMMAND_CENTER_DB_HOST", "")
    if host:
        user = demo_cc.get("DEMO_COMMAND_CENTER_DB_USERNAME", "postgres")
        password = urlparse.quote(demo_cc.get("DEMO_COMMAND_CENTER_DB_PASSWORD", ""), safe="")
        port = demo_cc.get("DEMO_COMMAND_CENTER_DB_PORT", "5432")
        database = demo_cc.get("DEMO_COMMAND_CENTER_DB_DATABASE", "demo_command_center")
        return f"postgresql+asyncpg://{user}:{password}@{host}:{port}/{database}"
    # Last resort: the Lead Intake instance, converted to asyncpg.
    lead_dsn = lead.get("DATABASE_URL", "")
    if not lead_dsn:
        return "postgresql+asyncpg://tmm:tmm@localhost:5433/tmm"
    parsed = urlparse.urlparse(lead_dsn)
    userinfo = parsed.username or "postgres"
    if parsed.password:
        userinfo = f"{userinfo}:{urlparse.quote(parsed.password, safe='')}"
    port = f":{parsed.port}" if parsed.port else ""
    return f"postgresql+asyncpg://{userinfo}@{parsed.hostname}{port}/tutormatch"


